// Interleaves batch files from parallel generate.js runs into levels.js.
// Usage: node tools/merge.js a.json b.json c.json d.json
const fs = require('fs');
const batches = process.argv.slice(2).map(f => JSON.parse(fs.readFileSync(f, 'utf8')));
const out = [];
for (let i = 0; batches.some(b => i < b.length); i++) for (const b of batches) if (i < b.length) out.push(b[i]);
fs.writeFileSync(__dirname + '/../levels.js', '// generated by tools/generate.js + tools/merge.js — do not edit\nwindow.TAB_LEVELS=' + JSON.stringify(out) + ';\n');
console.log('merged', out.length, 'levels; pars', [1, 2, 3].map(p => out.filter(l => l.par === p).length).join('/'));
